import os
import time

import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.getenv(
    "DATABASE_URL", "postgresql://restaurant:restaurant-dev-password@localhost:5432/restaurant"
)


def _connect():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_db():
    for attempt in range(30):
        try:
            with _connect() as conn:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        total NUMERIC(12, 2) NOT NULL,
                        status TEXT NOT NULL,
                        user_id BIGINT NOT NULL,
                        created_at TIMESTAMPTZ NOT NULL
                    )
                """)
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS order_items (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
                        product_id BIGINT NOT NULL,
                        name TEXT NOT NULL,
                        quantity INTEGER NOT NULL CHECK (quantity > 0),
                        unit_price NUMERIC(10, 2) NOT NULL,
                        subtotal NUMERIC(12, 2) NOT NULL
                    )
                """)
            return
        except psycopg.OperationalError:
            if attempt == 29:
                raise
            time.sleep(2)


def _as_order(row, items):
    if row is None:
        return None
    row["total"] = float(row["total"])
    row["created_at"] = row["created_at"].isoformat()
    row["items"] = [{
        "product_id": item["product_id"],
        "name": item["name"],
        "quantity": item["quantity"],
        "unit_price": float(item["unit_price"]),
        "subtotal": float(item["subtotal"]),
    } for item in items]
    return row


def _items(conn, order_id):
    return conn.execute("""
        SELECT product_id, name, quantity, unit_price, subtotal
        FROM order_items WHERE order_id=%s ORDER BY id
    """, (order_id,)).fetchall()


def create(items, total, status, user_id, created_at):
    with _connect() as conn:
        row = conn.execute("""
            INSERT INTO orders (total, status, user_id, created_at)
            VALUES (%s, %s, %s, %s) RETURNING *
        """, (total, status, user_id, created_at)).fetchone()
        with conn.cursor() as cursor:
            cursor.executemany("""
                INSERT INTO order_items (order_id, product_id, name, quantity, unit_price, subtotal)
                VALUES (%s, %s, %s, %s, %s, %s)
            """, [(row["id"], item["product_id"], item["name"], item["quantity"],
                   item["unit_price"], item["subtotal"]) for item in items])
        return _as_order(row, items)


def get_all():
    with _connect() as conn:
        rows = conn.execute("SELECT * FROM orders ORDER BY id DESC").fetchall()
        return [_as_order(row, _items(conn, row["id"])) for row in rows]


def get_by_id(order_id):
    with _connect() as conn:
        row = conn.execute("SELECT * FROM orders WHERE id=%s", (order_id,)).fetchone()
        return _as_order(row, _items(conn, order_id)) if row else None


def update_status(order_id, status):
    with _connect() as conn:
        row = conn.execute("UPDATE orders SET status=%s WHERE id=%s RETURNING *", (status, order_id)).fetchone()
        return _as_order(row, _items(conn, order_id)) if row else None


def update_items(order_id, items, total):
    with _connect() as conn:
        row = conn.execute("UPDATE orders SET total=%s WHERE id=%s AND status='CRIADO' RETURNING *", (total, order_id)).fetchone()
        if row is None:
            return None
        conn.execute("DELETE FROM order_items WHERE order_id=%s", (order_id,))
        with conn.cursor() as cursor:
            cursor.executemany("""
                INSERT INTO order_items (order_id, product_id, name, quantity, unit_price, subtotal)
                VALUES (%s, %s, %s, %s, %s, %s)
            """, [(order_id, item["product_id"], item["name"], item["quantity"],
                   item["unit_price"], item["subtotal"]) for item in items])
        return _as_order(row, items)


def delete(order_id):
    with _connect() as conn:
        return conn.execute("DELETE FROM orders WHERE id=%s RETURNING id", (order_id,)).fetchone()
