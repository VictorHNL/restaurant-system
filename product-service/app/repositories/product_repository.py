def _connect():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_db():
    for attempt in range(30):
        try:
            with _connect() as conn:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS products (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        description TEXT NOT NULL DEFAULT '',
                        price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
                        category TEXT NOT NULL DEFAULT 'Outros',
                        available BOOLEAN NOT NULL DEFAULT TRUE
                    )
                """)
                with conn.cursor() as cursor:
                    cursor.executemany("""
                        INSERT INTO products (id, name, description, price, category, available)
                        VALUES (%s, %s, %s, %s, %s, %s) ON CONFLICT (id) DO NOTHING
                    """, SEED_PRODUCTS)
                conn.execute("""
                    SELECT setval(pg_get_serial_sequence('products', 'id'),
                                  GREATEST(COALESCE((SELECT MAX(id) FROM products), 1), 1),
                                  EXISTS(SELECT 1 FROM products))
                """)
            return
        except psycopg.OperationalError:
            if attempt == 29:
                raise
            time.sleep(2)


def get_all():
    with _connect() as conn:
        return conn.execute("SELECT id, name, description, price::float AS price, category, available FROM products ORDER BY id").fetchall()


def get_by_id(product_id: int):
    with _connect() as conn:
        return conn.execute("SELECT id, name, description, price::float AS price, category, available FROM products WHERE id = %s", (product_id,)).fetchone()


def create(product_data):
    with _connect() as conn:
        return conn.execute("""
            INSERT INTO products (name, description, price, category, available)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id, name, description, price::float AS price, category, available
        """, (product_data.name, product_data.description, product_data.price,
              product_data.category, product_data.available)).fetchone()


def update(product_id: int, product_data):
    with _connect() as conn:
        return conn.execute("""
            UPDATE products SET name=%s, description=%s, price=%s, category=%s, available=%s
            WHERE id=%s
            RETURNING id, name, description, price::float AS price, category, available
        """, (product_data.name, product_data.description, product_data.price,
              product_data.category, product_data.available, product_id)).fetchone()


def delete(product_id: int):
    with _connect() as conn:
        return conn.execute("""
            DELETE FROM products WHERE id=%s
            RETURNING id, name, description, price::float AS price, category, available
        """, (product_id,)).fetchone()
