import base64, hashlib, hmac, json, os, secrets, time
from contextlib import asynccontextmanager
import asyncio
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, EmailStr, Field

SECRET = os.getenv("JWT_SECRET", "development-secret-change-in-production").encode()
DATABASE_URL = os.getenv("DATABASE_URL", "postgresql://restaurant:restaurant-dev-password@localhost:5432/restaurant")

def connect():
    import psycopg
    return psycopg.connect(DATABASE_URL)

@asynccontextmanager
async def lifespan(app):
    import psycopg
    for attempt in range(30):
        try:
            with connect() as conn:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        email TEXT NOT NULL UNIQUE,
                        password_hash TEXT NOT NULL
                    )
                """)
            break
        except psycopg.OperationalError:
            if attempt == 29:
                raise
            await asyncio.sleep(2)
    yield

app = FastAPI(title="User Service", lifespan=lifespan)
app.add_middleware(CORSMiddleware, allow_origins=os.getenv("CORS_ORIGINS","http://localhost:5178,http://127.0.0.1:5178,http://localhost:5173,http://127.0.0.1:5173").split(","), allow_methods=["*"], allow_headers=["*"])

class Register(BaseModel):
    name: str = Field(min_length=2, max_length=100)
    email: EmailStr
    password: str = Field(min_length=6, max_length=128)
class Login(BaseModel):
    email: EmailStr
    password: str

def password_hash(value: str, salt: str | None = None):
    salt = salt or secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", value.encode(), salt.encode(), 200_000).hex()
    return salt + "$" + digest
def password_ok(value: str, stored: str):
    salt, digest = stored.split("$", 1)
    return hmac.compare_digest(password_hash(value, salt), salt + "$" + digest)
def token_for(user):
    payload = base64.urlsafe_b64encode(json.dumps({"sub":user["id"],"email":user["email"],"exp":int(time.time())+3600}).encode()).decode().rstrip("=")
    signature = hmac.new(SECRET, payload.encode(), hashlib.sha256).hexdigest()
    return payload + "." + signature

@app.post("/auth/register", status_code=201)
def register(data: Register):
    key = data.email.lower()
    import psycopg
    try:
        with connect() as conn:
            user = conn.execute("""
                INSERT INTO users (name, email, password_hash) VALUES (%s, %s, %s)
                RETURNING id, name, email, password_hash
            """, (data.name, key, password_hash(data.password))).fetchone()
    except psycopg.errors.UniqueViolation:
        raise HTTPException(409, "Este e-mail já possui uma conta")
    user = dict(id=user[0], name=user[1], email=user[2], password=user[3])
    return {"token": token_for(user), "user": {"id": user["id"], "name":user["name"], "email":key}}
@app.post("/auth/login")
def login(data: Login):
    with connect() as conn:
        row = conn.execute("SELECT id, name, email, password_hash FROM users WHERE email=%s", (data.email.lower(),)).fetchone()
    if not row or not password_ok(data.password, row[3]): raise HTTPException(401, "E-mail ou senha inválidos")
    user = dict(id=row[0], name=row[1], email=row[2])
    return {"token": token_for(user), "user":user}
